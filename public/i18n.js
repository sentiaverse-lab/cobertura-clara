// Idioma actual (detecta del navegador, por defecto es)
let LANG = (navigator.language || 'es').toLowerCase().startsWith('en') ? 'en' : 'es';

function t(key, ...args) {
  const val = (I18N[LANG] && I18N[LANG][key]) ?? (I18N.es[key]);
  return typeof val === 'function' ? val(...args) : val;
}
function getLang() { return LANG; }
function setLang(l) { LANG = (l === 'en') ? 'en' : 'es'; }
